def get_golden_example(doc_type: str, part: str) -> str:
    """Возвращает эталонный пример для конкретной части работы."""
    if part == "intro":
        return GOLDEN_EXAMPLES["intro"]
    if part == "chapter":
        return GOLDEN_EXAMPLES["chapter"]
    if part == "conclusion":
        return GOLDEN_EXAMPLES["conclusion"]
    if part == "bibliography":
        return GOLDEN_EXAMPLES["bibliography"]
    return ""
